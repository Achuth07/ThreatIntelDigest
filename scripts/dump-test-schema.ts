// Writes tests/fixtures/schema.sql: the production structure of the tables the v1 API reads,
// read from the live catalog rather than shared/schema.ts (production differs from it, e.g. the
// CVSS columns are text). Read-only. Run again after a migration touches these tables:
//   npx tsx scripts/dump-test-schema.ts
import 'dotenv/config';
import { writeFileSync } from 'node:fs';
import { Pool, neonConfig } from '@neondatabase/serverless';
import ws from 'ws';

neonConfig.webSocketConstructor = ws;

export const TEST_TABLES = [
  'users', 'vulnerabilities', 'cve_scores', 'known_exploited_vulnerabilities', 'vendors', 'products',
  'cve_products', 'article_cves', 'threat_groups', 'actor_cves', 'api_keys', 'api_rate_limits',
];

const pool = new Pool({ connectionString: process.env.DATABASE_URL });

async function main() {
  const out: string[] = ['-- Generated by scripts/dump-test-schema.ts. Do not edit by hand.', ''];
  for (const table of TEST_TABLES) {
    const { rows: cols } = await pool.query(`
      SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS not_null,
             pg_get_expr(d.adbin, d.adrelid) AS default_expr
      FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE n.nspname = 'public' AND c.relname = $1 AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum`, [table]);
    if (!cols.length) throw new Error(`Table ${table} not found`);
    const lines = cols.map((col: any) => {
      let type = col.type;
      let def = col.default_expr as string | null;
      if (def?.startsWith('nextval(')) { type = type === 'bigint' ? 'bigserial' : 'serial'; def = null; }
      return `  "${col.name}" ${type}${col.not_null ? ' NOT NULL' : ''}${def ? ` DEFAULT ${def}` : ''}`;
    });
    // Primary key, unique and check constraints. Foreign keys are left out so tests can seed
    // tables independently.
    const { rows: cons } = await pool.query(`
      SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint
      WHERE conrelid = $1::regclass AND contype IN ('p', 'u', 'c') ORDER BY contype, conname`, [table]);
    for (const con of cons) lines.push(`  CONSTRAINT "${con.conname}" ${con.def}`);
    out.push(`CREATE TABLE "${table}" (\n${lines.join(',\n')}\n);`);
    const { rows: idx } = await pool.query(`
      SELECT i.indexdef FROM pg_indexes i
      WHERE i.schemaname = 'public' AND i.tablename = $1
        AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conname = i.indexname AND c.conrelid = $1::regclass)
      ORDER BY i.indexname`, [table]);
    for (const row of idx) out.push(`${row.indexdef.replace(/ public\./g, ' ')};`);
    out.push('');
  }
  writeFileSync('tests/fixtures/schema.sql', out.join('\n'));
  console.log(`Wrote ${TEST_TABLES.length} tables to tests/fixtures/schema.sql`);
  await pool.end();
}

main().catch(error => { console.error(error); process.exit(1); });
